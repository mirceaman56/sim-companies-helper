/**
 * Detect language from the current page URL.
 * Returns language code based on path prefix, defaults to "en".
 */
function detectLang() {
  try {
    const path = window.location.pathname;
    const langCodes = {
      "/de": "de",
      "/fr": "fr",
      "/pt": "pt",
      "/tr": "tr",
      "/it": "it",
      "/es": "es",
      "/zh-cn": "zh_cn",
      "/zh-tw": "zh_tw",
      "/cs": "cs",
      "/pl": "pl",
      "/ja": "ja",
    };
    for (const [prefix, code] of Object.entries(langCodes)) {
      if (path.startsWith(prefix)) return code;
    }
    return "en";
  } catch {
    return "en";
  }
}

const currentLang = detectLang();

/**
 * Get a translated string by key.
 * Falls back to English if key is missing in the current language.
 * @param {string} key
 * @returns {string}
 */
export function t(key) {
  return STRINGS[currentLang]?.[key] ?? STRINGS.en[key] ?? key;
}

/**
 * Get the current detected language code.
 * @returns {"en"|"de"|"fr"|"pt"|"tr"|"it"|"es"|"zh_cn"|"zh_tw"|"cs"|"pl"|"ja"}
 */
export function getLang() {
  return currentLang;
}

/**
 * Parse a locale-formatted number string into a JS number.
 * German: "." = thousands, "," = decimal  (e.g. "31.825" → 31825, "1,95" → 1.95)
 * English: "," = thousands, "." = decimal (e.g. "31,825" → 31825, "1.95" → 1.95)
 * @param {string} raw
 * @returns {number}
 */
export function parseLocalNumber(raw) {
  let s = String(raw).trim();
  if (currentLang === "de") {
    // Remove thousands separator (.) then swap decimal comma → dot
    s = s.replace(/\./g, "").replace(/,/, ".");
  } else {
    // Remove thousands separator (,)
    s = s.replace(/,/g, "");
  }
  const m = s.match(/-?\s*([0-9]+(?:\.[0-9]+)?)/);
  return m ? Number(m[1]) : NaN;
}
